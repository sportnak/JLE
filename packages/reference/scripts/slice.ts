// Writes the word list the app loads at startup: the most frequent content words from reference.sqlite,
// plus the JMdict entry each starter word maps to. Run after build:db.
//   node scripts/slice.ts [--limit 20000]
import { DatabaseSync } from 'node:sqlite';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { STARTER_VOCAB } from '../../seed/src/vocab.ts';
import { engineGloss, enginePos, isFunctionWord, isWordReading, pickEntry, type Candidate } from '../src/slice.ts';

const here = dirname(fileURLToPath(import.meta.url));
const dbPath = join(here, '../out/reference.sqlite');
const outPath = join(here, '../../seed/src/data/words.json');
const limitArg = process.argv.indexOf('--limit');
const LIMIT = limitArg > 0 ? Number(process.argv[limitArg + 1]) : 20_000;

const db = new DatabaseSync(dbPath, { readOnly: true });
const meta = Object.fromEntries(
  (db.prepare('SELECT key, value FROM meta').all() as { key: string; value: string }[]).map((r) => [r.key, r.value]),
);

interface Row {
  id: number;
  written: string;
  reading: string;
  kana_only: number;
  freq_rank: number | null;
  priority: string;
  pos: string;
  gloss: string;
}

const byId = db.prepare('SELECT id, written, reading, kana_only, freq_rank, priority, pos, gloss FROM entry WHERE id = ?');
const candidates = db.prepare(`
  SELECT e.id, e.freq_rank AS rank, e.priority, w.is_primary AS primaryForm
  FROM form w JOIN entry e ON e.id = w.entry_id
  WHERE w.text = ?
    AND EXISTS (
      SELECT 1 FROM form r
      WHERE r.entry_id = e.id AND r.kind = 'kana' AND r.text = ?
        AND (w.kind = 'kana' OR r.restr IS NULL OR EXISTS (SELECT 1 FROM json_each(r.restr) j WHERE j.value = w.text))
    )
  GROUP BY e.id`);

// Starter words first, in their hand-made order.
const aliases: Record<string, string> = {};
const starterIds: number[] = [];
const unmatched: string[] = [];
for (const [written, reading] of STARTER_VOCAB) {
  const found = pickEntry(candidates.all(written, reading) as unknown as Candidate[]);
  if (!found) {
    unmatched.push(`${written}【${reading}】`);
    continue;
  }
  aliases[`vocab:${written}`] = `jmdict:${found}`;
  if (!starterIds.includes(found)) starterIds.push(found);
}
if (unmatched.length) {
  console.error(`No entry for: ${unmatched.join(' ')}`);
  process.exit(1);
}

const ranked = db.prepare('SELECT id, written, reading, kana_only, freq_rank, priority, pos, gloss FROM entry WHERE freq_rank IS NOT NULL ORDER BY freq_rank').all() as unknown as Row[];
const starter = new Set(starterIds);
const rest: Row[] = [];
let skippedFunction = 0;
let skippedSymbols = 0;
for (const r of ranked) {
  if (rest.length >= LIMIT) break;
  if (starter.has(r.id)) continue;
  if (!isWordReading(r.reading)) {
    skippedSymbols++;
    continue;
  }
  if (isFunctionWord(JSON.parse(r.pos))) {
    skippedFunction++;
    continue;
  }
  rest.push(r);
}

const toWord = (r: Row) => {
  const pos = enginePos(JSON.parse(r.pos));
  return [r.id, r.kana_only ? r.reading : r.written, r.reading, r.freq_rank ?? 0, engineGloss(JSON.parse(r.gloss)), ...(pos ? [pos] : [])];
};

const words = [...starterIds.map((id) => byId.get(id) as unknown as Row), ...rest].map(toWord);
mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(
  outPath,
  JSON.stringify({
    about: 'Generated by packages/reference/scripts/slice.ts from reference.sqlite. Do not edit.',
    attribution: meta['attribution'] ?? '',
    sources: Object.fromEntries(Object.entries(meta).filter(([k]) => /date|version|sha256/i.test(k))),
    columns: ['jmdictId', 'written', 'reading', 'freqRank', 'gloss', 'pos?'],
    starterCount: starterIds.length,
    aliases,
    words,
  }) + '\n',
);
console.log(
  `${words.length} words (${starterIds.length} starter, ${rest.length} by frequency; ${skippedFunction} function words and ${skippedSymbols} symbols skipped) -> ${outPath}`,
);
